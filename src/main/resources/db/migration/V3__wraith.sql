-- 전생의 망령: 패배한 원정의 마지막 모습을 남겨, 다음 원정의 같은 자리에서 적으로 다시 만나게 한다.
--
-- 회원당 기다리는 망령(ACTIVE)은 하나뿐이다. 새로 쓰러지면 이전 망령은 FADED가 된다.
-- 처치하면 SLAIN, 세 번 달아나면 FADED.
-- memories는 그 원정에서 내린 선택 몇 줄이다(AI 대화 기록에서 복사). 대화 기록은 30일 뒤 파기되기 때문이다.
-- 탈퇴하면 회원의 행을 모두 지운다.

CREATE TABLE public.wraith (
    wraith_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    member_id bigint NOT NULL,
    source_game_state_id bigint NOT NULL,
    stage smallint NOT NULL,
    node smallint NOT NULL,
    level integer NOT NULL,
    killer_name character varying(100),
    skills character varying(500),
    relic_ids character varying(200),
    faction character varying(10),
    memories text,
    escapes integer NOT NULL DEFAULT 0,
    status character varying(10) NOT NULL,
    created_at timestamp(6) without time zone NOT NULL,
    updated_at timestamp(6) without time zone,
    CONSTRAINT fk_wraith_member_memberId FOREIGN KEY (member_id) REFERENCES public.member (member_id),
    CONSTRAINT wraith_status_check CHECK (status IN ('ACTIVE', 'SLAIN', 'FADED'))
);

CREATE INDEX idx_wraith_member_status ON public.wraith (member_id, status);
