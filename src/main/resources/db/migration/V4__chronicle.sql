-- 레노바 연대기: 끝난 원정마다 한 장(章)씩 쌓이는 회원의 이야기책.
--
-- 장은 원정 종료 후 런 회고를 만들 때 함께 쓴다(같은 LLM 호출, 구조화 출력의 필드 두 개).
-- 회고를 만들지 못하면 서버가 사실만으로 쓴 짧은 장을 남긴다. 원정 하나에 장 하나.
-- 탈퇴하면 회원의 장을 모두 지운다.

CREATE TABLE public.chronicle_chapter (
    chapter_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    member_id bigint NOT NULL,
    game_state_id bigint NOT NULL,
    chapter_no integer NOT NULL,
    title character varying(40) NOT NULL,
    body text NOT NULL,
    cleared boolean NOT NULL,
    stage smallint NOT NULL,
    node smallint NOT NULL,
    faction character varying(10),
    difficulty character varying(20) NOT NULL,
    created_at timestamp(6) without time zone NOT NULL,
    CONSTRAINT fk_chronicle_member_memberId FOREIGN KEY (member_id) REFERENCES public.member (member_id),
    CONSTRAINT uk_chronicle_game_state UNIQUE (game_state_id)
);

CREATE INDEX idx_chronicle_member ON public.chronicle_chapter (member_id, chapter_no);
